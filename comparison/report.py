"""Aggregate the trials in results/trials/ into RESULTS.md.

    cd plugin && uv run python ../comparison/report.py     # with PreCheck's code, to check its scripts compile the same
"""

import hashlib
import json
import statistics
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any, Dict, List

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parent / "plugin"))  # PreCheck's code, to compile its protocols
import score  # noqa: E402

TITLES = {"dna_extraction": "DNA extraction (nPOD SOP-79.1, section 1.0)", "serial_dilution": "Serial dilution (1:10 in saline)"}


def _mean(values: List[float]) -> str:
    v = [x for x in values if x is not None]
    return f"{statistics.mean(v):.2f}" if v else "–"


def _compiles_the_same(ir_path: str) -> Any:
    """PreCheck's protocol is fixed once written: compiling it twice gives the same script, byte for byte."""
    try:
        from pipeline.deck import DEFAULT_DECK, load_deck_config
        from pipeline.stage2_compiler import compile_standalone
    except ImportError:
        return None
    ir = Path(ir_path)
    protocol = json.loads(ir.read_text())
    deck = load_deck_config(str(ir.parent.parent / protocol.get("deck_config", DEFAULT_DECK)))
    digests = {hashlib.sha256(compile_standalone(protocol, deck, protocol.get("deck_config", DEFAULT_DECK), "x").encode()).hexdigest()
               for _ in range(2)}
    return len(digests) == 1


def main() -> None:
    trials = [json.loads(p.read_text()) for p in sorted((HERE / "results" / "trials").glob("*.json"))]
    trials = [t for t in trials if t.get("trial", 0) > 0]  # trial 0 is the smoke test
    groups: Dict[tuple, List[Dict[str, Any]]] = defaultdict(list)
    for t in trials:
        groups[(t["sop"], t["arm"])].append(t)
    lines = ["# PreCheck against an agent driving AHC: results", "",
             "Generated by `comparison/report.py` from `comparison/results/trials/`. Method: `comparison/README.md`.", ""]
    for sop in ("serial_dilution", "dna_extraction"):
        arms = {arm: ts for (s, arm), ts in groups.items() if s == sop}
        if not arms:
            continue
        lines += [f"## {TITLES[sop]}", "", f"Answer key: {score.KEYS[sop]['sop']}.", ""]
        head = ["", *arms]
        rows = []

        def row(label, fn):
            rows.append([label, *[fn(ts) for ts in arms.values()]])

        row("Trials", lambda ts: str(len(ts)))
        row("Produced a protocol / finished the run", lambda ts: f"{sum(1 for t in ts if t.get('passed', t.get('finished')))}/{len(ts)}")
        row("SOP fidelity (mean share of the key right)", lambda ts: _mean([t["score"]["fidelity"] for t in ts]))
        if sop == "dna_extraction":
            row("Key additions right, per trial", lambda ts: ", ".join(f"{t['score']['correct']}/{t['score']['of']}" for t in ts))
            row("In the SOP's order", lambda ts: f"{sum(1 for t in ts if t['score'].get('in_sop_order'))}/{len(ts)}")
            row("Samples", lambda ts: ", ".join(str(t["score"].get("samples")) for t in ts))
        else:
            row("Wells at 1:10 (or 1:11), per trial", lambda ts: ", ".join(f"{t['score']['correct']}/{t['score']['of']}" for t in ts))
            row("Dilution steps", lambda ts: ", ".join(str(t["score"].get("steps")) for t in ts))
        row("Distinct plans across trials", lambda ts: str(len({score.signature(t["score"]) for t in ts})))
        row("Problems found before a session (draft retries + repair rounds)", lambda ts: ", ".join(
            str(sum((t.get("draft_retries") or {}).values()) + (t.get("repair_rounds") or 0)) if "draft_retries" in t else "–" for t in ts))
        row("AHC calls refused during the session", lambda ts: ", ".join(
            str(sum(1 for r in t["refusals"] if r["tool"] != "open_dashboard")) if "refusals" in t else "–" for t in ts))
        row("Steps left to a person", lambda ts: ", ".join(str(t.get("manual_steps", "–")) for t in ts))
        row("Labware AHC cannot load", lambda ts: ", ".join(str(t.get("ahc_not_on_layout", "–")) for t in ts))
        row("Wall time (s, mean)", lambda ts: _mean([t.get("wall_s") for t in ts]))
        row("Model cost (USD, mean)", lambda ts: _mean([t.get("cost_usd", t.get("draft_cost_usd")) for t in ts]))
        lines += ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
        lines += ["| " + " | ".join(r) + " |" for r in rows] + [""]
        misses = defaultdict(int)
        for arm, ts in arms.items():
            for t in ts:
                for it in t["score"].get("items", []):
                    if not it["ok"]:
                        misses[(arm, it["item"])] += 1
        if misses:
            lines += ["Key additions missed or at the wrong volume:", ""]
            lines += [f"- {arm}: {item} ({n} of {len(arms[arm])} trials)" for (arm, item), n in sorted(misses.items())] + [""]
        same = [_compiles_the_same(t["ir"]) for ts in arms.values() for t in ts if t.get("ir")]
        if same and None not in same:
            lines += [f"PreCheck's written protocols compile to the same script every time: {sum(same)}/{len(same)}.", ""]
    (HERE / "RESULTS.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
